import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const entitiesDir = path.join(root, "content", "entities");

function writeCollection(name, items) {
  const dir = path.join(entitiesDir, name);
  fs.mkdirSync(dir, { recursive: true });
  for (const file of fs.readdirSync(dir)) {
    if (file.endsWith(".json")) fs.unlinkSync(path.join(dir, file));
  }
  for (const item of items) {
    fs.writeFileSync(
      path.join(dir, `${item.slug}.json`),
      `${JSON.stringify(item, null, 2)}\n`,
    );
  }
  console.log(`Wrote ${items.length} ${name}`);
}

